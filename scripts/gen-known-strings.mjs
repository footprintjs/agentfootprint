#!/usr/bin/env node
/**
 * gen-known-strings — writes the two literals of `src/redaction/knownStrings.ts`
 * (the library's own words, and its payloads' field names) from the TYPES that
 * file declares (`LibraryWord`, `FieldName`), so the closed sets are the code's
 * own unions. The compiler then checks the literals exactly against the types:
 * a word added to a payload union does not compile until this is re-run.
 *
 *   node scripts/gen-known-strings.mjs           write the literals
 *   node scripts/gen-known-strings.mjs --check   fail when they are stale
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ts = createRequire(import.meta.url)('typescript');
const file = join(root, 'src/redaction/knownStrings.ts');

const program = ts.createProgram([file], {
  target: ts.ScriptTarget.ES2022,
  module: ts.ModuleKind.NodeNext,
  moduleResolution: ts.ModuleResolutionKind.NodeNext,
  strict: true,
  skipLibCheck: true,
  noEmit: true,
});
const checker = program.getTypeChecker();
const source = program.getSourceFile(file);

/** The string literal members of the exported type alias `name`, sorted. */
function membersOf(name) {
  let members;
  ts.forEachChild(source, (node) => {
    if (ts.isTypeAliasDeclaration(node) && node.name.text === name) {
      const type = checker.getTypeAtLocation(node.name);
      const parts = type.isUnion() ? type.types : [type];
      members = parts.map((part) => {
        if (!part.isStringLiteral()) throw new Error(`${name}: a member is not a string literal`);
        return part.value;
      });
    }
  });
  if (members === undefined) throw new Error(`no type alias ${name}`);
  return [...new Set(members)].sort();
}

/**
 * A single-quoted key, escaped completely. JSON.stringify escapes backslashes and
 * control characters; the double quotes it escapes need no escape inside single
 * quotes, and the single quotes it leaves bare do.
 */
const quoted = (word) =>
  `'${JSON.stringify(word).slice(1, -1).replace(/\\"/g, '"').replace(/'/g, "\\'")}'`;
const key = (word) => (/^[A-Za-z_$][\w$]*$/.test(word) ? word : quoted(word));
/** One entry per line, as the repo's Prettier writes it (printWidth 100: a longer key breaks after the colon). */
const entry = (word) => {
  const line = `  ${key(word)}: true,`;
  return line.length > 100 ? `  ${key(word)}:\n    true,` : line;
};
const literal = (words) => words.map(entry).join('\n');

// Bounded literal shards: a generated vocabulary obeys the same 600-line
// ceiling as handwritten source. The combined map checks missing AND unknown
// keys; spreading shards must not weaken the old exact literal check.
const folder = join(root, 'src/redaction/knownStrings');
mkdirSync(folder, { recursive: true });
const outputs = new Map();
for (const [stem, type, exportName] of [
  ['words', 'LibraryWord', 'generatedWords'],
  ['fields', 'FieldName', 'generatedFields'],
]) {
  const words = membersOf(type);
  const chunks = [];
  for (let i = 0; i < words.length; i += 300) chunks.push(words.slice(i, i + 300));
  for (const [i, chunk] of chunks.entries()) {
    outputs.set(`${stem}-${i}.ts`, `// Generated by scripts/gen-known-strings.mjs.\nexport const ${stem}${i} = {\n${literal(chunk)}\n} as const;\n`);
  }
  const imports = chunks.map((_, i) => `import { ${stem}${i} } from './${stem}-${i}.js';`).join('\n');
  const keys = chunks.map((_, i) => `keyof typeof ${stem}${i}`).join(' | ');
  const spreads = chunks.map((_, i) => `  ...${stem}${i},`).join('\n');
  outputs.set(`${stem}.ts`, `// Generated by scripts/gen-known-strings.mjs.\nimport type { ${type} } from '../knownStrings.js';\n${imports}\ntype Keys = ${keys};\nexport const ${exportName}: { readonly [K in ${type} | Keys]: K extends ${type} ? true : never } = {\n${spreads}\n};\n`);
}
let stale = false;
const prettier = createRequire(import.meta.url)('prettier');
const style = createRequire(import.meta.url)(join(root, '.prettierrc.js'));
for (const [name, source] of outputs) {
  const next = await prettier.format(source, { ...style, parser: 'typescript' });
  const destination = join(folder, name);
  let current;
  try { current = readFileSync(destination, 'utf8'); } catch { current = undefined; }
  if (process.argv.includes('--check')) {
    if (current !== next) { console.error(`stale vocabulary: ${name}`); stale = true; }
  } else writeFileSync(destination, next);
}
if (stale) process.exit(1);
console.log(process.argv.includes('--check') ? 'known strings are up to date ✓' : 'wrote bounded known-string maps');
