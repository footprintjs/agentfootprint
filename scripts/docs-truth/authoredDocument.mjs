/** Return the verified whole-document generator, without running any script. */
export function generatedDocumentScript(raw, scripts = {}) {
  const header = raw
    .trimStart()
    .replace(/^# [^\r\n]*(?:\r?\n|$)/, '')
    .trimStart();
  const match = /^<!-- GENERATED by npm run ([A-Za-z0-9:._-]+); do not edit\. -->(?:\r?\n|$)/.exec(
    header,
  );
  if (!match || !Object.hasOwn(scripts, match[1]) || typeof scripts[match[1]] !== 'string')
    return undefined;
  const pending = ['docs:generate'];
  const visited = new Set();
  while (pending.length) {
    const name = pending.pop();
    if (visited.has(name) || typeof scripts[name] !== 'string') continue;
    visited.add(name);
    if (name === match[1]) return name;
    for (const command of scripts[name].split('&&')) {
      const edge = /^\s*npm\s+(?:run|run-script)\s+([A-Za-z0-9:._-]+)(?:\s|$)/.exec(command);
      if (edge && Object.hasOwn(scripts, edge[1])) pending.push(edge[1]);
    }
  }
  return undefined;
}

/** A marker with no proved generation route remains authored evidence. */
export function isAuthoredDocument(raw, scripts = {}) {
  return generatedDocumentScript(raw, scripts) === undefined;
}
