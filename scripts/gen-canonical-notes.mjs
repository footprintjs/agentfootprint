/**
 * gen-canonical-notes — publish the canonical wire strings as DATA.
 *
 * ## Why this file exists
 *
 * `absent()`, `coverage()` and `semantic()` mint shapes that carry a STATIC,
 * never-interpolated sentence, and a reserved marker key that makes each shape
 * recognizable. Those bytes are a contract: a recognizer accepts the marker
 * verbatim, and the note is what the docs promise a model will read.
 *
 * A tool that is not written in JavaScript has to reproduce them exactly. In
 * the field, a Python sidecar did the only thing the package made possible —
 * it regex-scraped the compiled ESM under `node_modules/agentfootprint/dist/esm`
 * at import time. That instinct was right (read the value, never copy it; fail
 * loudly if it moves) and the door was wrong, and the wrong door was ours. So
 * we publish the strings as a JSON file any language can `open()`.
 *
 * ## Why it is GENERATED, and generated from the BUILT package
 *
 * A hand-maintained copy of a canonical string is the drift this is supposed
 * to end — it would be a second spelling of a value whose whole job is to have
 * one. So the file is written from `dist/esm/index.js`: the very module a
 * consumer imports, after both compiles and after `postbuild-esm`. The JSON
 * therefore cannot disagree with the code a release ships, because it is read
 * out of it.
 *
 * `test/docs/canonical-notes.test.ts` pins the other direction (every value
 * byte-equals the exported constant, and the file is in the packed tarball),
 * so a constant edited without a rebuild fails the suite rather than shipping
 * a stale file.
 *
 * ## What is in it, and what is deliberately not
 *
 * `GROUPS` below is the one curated decision here — WHICH constants belong.
 * The bar is: a string another process must reproduce or match BYTE FOR BYTE
 * to interoperate. That is the three notes (minted onto the wire), the three
 * markers (the reserved keys a strict recognizer requires), and the coverage
 * block's heading (the line a reader matches to find the block in an answer).
 *
 * Model-facing prose the library injects for itself — `WRAP_UP_INSTRUCTION`,
 * `NO_TOOL_VALUE`, the check-up boundary notes — is deliberately OUT. No
 * foreign process mints those; publishing them would turn an interop contract
 * into an inventory of every string in the package.
 *
 * Values only, no version stamp: `release.sh` bumps `package.json` around the
 * build, so a version copied in here could be one release stale. A consumer
 * that needs the version reads `package.json`, which the exports map publishes.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { resolve, dirname, relative } from 'node:path';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const BARREL = resolve(ROOT, 'dist', 'esm', 'index.js');
const OUT = resolve(ROOT, 'canonical-notes.json');

/** The curated membership list. See the header for the bar it applies. */
const GROUPS = {
  notes: ['ABSENCE_NOTE', 'COVERAGE_NOTE', 'SEMANTICS_NOTE'],
  markers: ['ABSENCE_MARKER', 'COVERAGE_MARKER', 'SEMANTICS_MARKER'],
  headings: ['COVERAGE_BLOCK_HEADING'],
};

const barrel = await import(pathToFileURL(BARREL).href).catch((err) => {
  throw new Error(
    `gen-canonical-notes: could not load ${relative(ROOT, BARREL)} — run \`npm run build\` ` +
      `first (this script reads the BUILT package on purpose, so the JSON cannot disagree ` +
      `with what ships). Cause: ${err instanceof Error ? err.message : String(err)}`,
  );
});

const out = {
  $comment:
    "GENERATED by scripts/gen-canonical-notes.mjs from this package's own built exports - " +
    'do not edit by hand. These are the strings a tool written in another language must ' +
    'reproduce byte for byte: the static notes each result shape carries, the reserved marker ' +
    "keys that make those shapes recognizable, and the coverage block's heading. Keys are " +
    'the exported constant names, so the same value is reachable as a TypeScript import from ' +
    "the package's main entry point. The package version lives in package.json.",
};

for (const [group, names] of Object.entries(GROUPS)) {
  const bag = {};
  for (const name of names) {
    const value = barrel[name];
    if (typeof value !== 'string' || value.length === 0) {
      // Fail LOUD rather than emit a hole — the postbuild-esm law. A constant
      // that was renamed, un-exported or emptied must stop the build here,
      // where the message can name it, not at a consumer's `KeyError`.
      throw new Error(
        `gen-canonical-notes: the main barrel does not export a non-empty string named ` +
          `'${name}' (got ${JSON.stringify(value)}). If the constant was renamed or moved off ` +
          `the barrel, update GROUPS in this script — and know that removing it from the JSON ` +
          `is a breaking change for every non-JS consumer reading it.`,
      );
    }
    bag[name] = value;
  }
  out[group] = bag;
}

writeFileSync(OUT, JSON.stringify(out, null, 2) + '\n');

const count = Object.values(GROUPS).reduce((n, names) => n + names.length, 0);
console.log(`gen-canonical-notes: ${relative(ROOT, OUT)} — ${count} canonical strings ✓`);
