import { sourceOrder } from './methods.mjs';
const cell = (value) =>
  String(value)
    .replace(/[\\`*_[\]~|]/g, '\\$&')
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replace(/\r?\n/g, '<br>');
const source = (row) =>
  `[${cell(row.file)}:${row.line}](../${row.file.split('/').map(encodeURIComponent).join('/')}#L${
    row.line
  })`;
const condition = (row) =>
  row.context.length
    ? row.context.map(cell).join('; ')
    : 'No recorded enclosing source control; caller execution is not inferred.';
const description = (row) =>
  !row.description
    ? 'Source description not recorded'
    : row.description.state === 'absent'
    ? 'Not supplied at this declaration'
    : row.description.state === 'expression'
    ? `Expression: ${cell(row.description.text)}`
    : row.description.text.trim() === ''
    ? 'Empty literal'
    : cell(row.description.text);

export function renderChartMap(inventory) {
  const mounts = [...inventory.mounts];
  const stages = [...inventory.stages];
  mounts.sort(sourceOrder);
  stages.sort(sourceOrder);
  const proven = mounts.filter((row) => row.certainty === 'engine').length;
  const absent = stages.filter((row) => row.description.state === 'absent');
  const empty = stages.filter(
    (row) => row.description.state === 'literal' && row.description.text.trim() === '',
  );
  const dynamic = stages.filter((row) => row.description.state === 'expression');
  const lines = [
    '# Declared chart map',
    '',
    '<!-- GENERATED by npm run docs:chart-map; do not edit. -->',
    '',
    'This is a read-only index of production TypeScript source declarations, selected by the repository tsconfig. It does not execute application code, build a configured agent, or run stages, tools, providers or lazy resolvers.',
    '',
    `Found **${
      mounts.length
    } mount declaration sites** (${proven} compiler-resolved engine calls, ${
      mounts.length - proven
    } unresolved structural ports) and **${
      stages.length
    } chart/stage declaration sites**. These are source sites, not runtime placements; repeated IDs and repeated source placements are retained. No historical mount count is enforced.`,
    '',
    'Enclosing source conditions and loops are shown without deciding their outcome. Early returns, caller-supplied graphs, lazy expansion and runtime multiplicity remain unresolved. Expressions ending in “see source” are abbreviated display text; each row links to the complete source.',
    '',
    'Descriptions below report source arguments only. “Not supplied” does not prove that built metadata has no description: an eager child or another declaration can supply inherited text. Unknown expressions are kept distinct from absent and empty literals. The separate description-enforcement task is not applied here.',
    '',
    '## Mount declarations',
    '',
    '| Declaration | Builder/factory | Method | Declared ID | Child chart expression | Mount name | Explicit description | Enclosing control | Origin |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- |',
  ];
  for (const row of mounts) {
    lines.push(
      `| ${source(row)} | ${cell(row.owner)} | ${cell(row.method)} | ${cell(row.id)} | ${cell(
        row.target,
      )} | ${cell(row.mountName)} | ${description(row)} | ${condition(row)} | ${cell(
        row.certainty,
      )} |`,
    );
  }
  lines.push(
    '',
    '## Chart and stage descriptions',
    '',
    `${absent.length} declarations have no explicit description argument/options property; ${empty.length} have an empty literal; ${dynamic.length} have a description expression whose runtime text is not inferred.`,
    '',
    '| Declaration | Builder/factory | Method | Declared ID | Name | Explicit description | Enclosing control | Origin |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |',
  );
  for (const row of stages) {
    lines.push(
      `| ${source(row)} | ${cell(row.owner)} | ${cell(row.method)} | ${cell(row.id)} | ${cell(
        row.name,
      )} | ${description(row)} | ${condition(row)} | ${cell(row.certainty)} |`,
    );
  }
  lines.push(
    '',
    '## Description gaps in source declarations',
    '',
    'These rows identify absent or empty source text for follow-up. They do not assert that a configured chart lacks inherited metadata.',
    '',
    '| Declaration | Builder/factory | Method | Declared ID | Source gap |',
    '| --- | --- | --- | --- | --- |',
  );
  for (const row of stages.filter((row) => absent.includes(row) || empty.includes(row))) {
    lines.push(
      `| ${source(row)} | ${cell(row.owner)} | ${cell(row.method)} | ${cell(
        row.id,
      )} | ${description(row)} |`,
    );
  }
  return lines.join('\n') + '\n';
}
