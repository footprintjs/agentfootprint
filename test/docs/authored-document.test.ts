import { describe, expect, it } from 'vitest';
import { isAuthoredDocument } from '../../scripts/docs-truth/authoredDocument.mjs';
import { renderChartMap } from '../../scripts/chart-map/index.mjs';

describe('authored documentation evidence', () => {
  it.each([
    ['comment header', '<!-- GENERATED by an indexer; do not edit. -->\nA source symbol.'],
    ['title then marker', '# Index\n\n<!-- GENERATED by a source collector. -->\nA symbol.'],
    ['derived header', '<!-- DERIVED by a generator. -->\nA symbol.'],
    ['BOM and CRLF', '\uFEFF# Index\r\n\r\n<!-- GENERATED by a collector. -->'],
  ])('does not credit a whole generated document: %s', (_name, page) => {
    expect(isAuthoredDocument(page)).toBe(false);
  });

  it('does not treat the real generated chart map as authored explanations', () => {
    expect(isAuthoredDocument(renderChartMap({ mounts: [], stages: [] }))).toBe(false);
  });

  it.each([
    '# Guide\nUse Agent to build the application.',
    '# Guide\n\nThis paragraph explains a symbol.\n<!-- GENERATED by a section indexer. -->',
    '# Guide\n\n```md\n<!-- GENERATED by an example. -->\n```',
    '# Guide\n\n> <!-- GENERATED by an example. -->',
    '# Guide\n\n<!-- GENERATED examples are discussed below. -->\nAn authored explanation.',
  ])('keeps authored prose and quoted or section-level markers: %s', (page) => {
    expect(isAuthoredDocument(page)).toBe(true);
  });
});
