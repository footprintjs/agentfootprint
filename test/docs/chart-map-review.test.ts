import { spawnSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { mkdtempSync, mkdirSync, symlinkSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { beforeAll, afterAll, it, expect } from 'vitest';
import { collectChartMap, renderChartMap } from '../../scripts/chart-map/index.mjs';
import { isAuthoredDocument } from '../../scripts/docs-truth/authoredDocument.mjs';

let root: string;
let rows: ReturnType<typeof collectChartMap>;
const fixture =
  "import { flowChart, flowChartSelector } from 'footprintjs';\nconst fn = () => { throw new Error('Must not execute'); };\ndeclare const on: boolean, values: string[], rest: any[], maybe: any;\nconst b = flowChart('Root', fn, 'root');\ninterface ProcessPort { start(input: { key: string }): void; }\ndeclare const processPort: ProcessPort;\nprocessPort.start({ key: 'ordinary-port-input' });\nflowChartSelector('Selector', fn, 'selector-root', { description: 'Root text.' });\nb.addParallelForEach('Fan out', 'fan-id', { items: () => [], branch: () => b.build() }, 'Fan text.');\nb.addStreamingFunction('Stream', fn, 'stream-id', 'stream-channel', 'Stream description.');\nb.addPausableFunction('Pause', { execute: fn, resume: fn }, 'pause-id');\nb.addListOfFunction([]);\nb.startSelector('Start', fn, 'start-id');\nb.addRetryLoop('retry-id', {} as any);\nb.addDetachAndForget('forget-id', b.build(), {} as any);\nb.addDetachAndJoinLater('join-id', b.build(), {} as any);\nif (on) b.addFunction('Conditional', fn, 'conditional');\nvalues.forEach(() => b.addFunction('Callback', fn, 'callback'));\nswitch (on) { case true: b.addFunction('Switch', fn, 'switch'); break; }\non && b.addFunction('Logical', fn, 'logical');\ntry {} catch { b.addFunction('Catch', fn, 'catch'); }\nb?.addFunction('Optional', fn, 'optional');\nb.addFunction(...(['spread-all', fn, 'spread-all-id', 'Spread text.'] as const));\nb.addFunction('spread-tail', fn, ...rest);\ndeclare const mixed: typeof b & { addFunction(name: 'Local', fn: () => void, id: string): void };\nconst bound = mixed.addFunction.bind(mixed);\nbound('Local', fn, 'mixed-bound');\n";
beforeAll(() => {
  root = mkdtempSync(join(tmpdir(), 'hci-map-review-'));
  mkdirSync(join(root, 'src'));
  symlinkSync(join(resolve(__dirname, '../..'), 'node_modules'), join(root, 'node_modules'), 'dir');
  writeFileSync(
    join(root, 'tsconfig.json'),
    JSON.stringify({
      compilerOptions: {
        target: 'ES2022',
        module: 'commonjs',
        moduleResolution: 'node',
        strict: true,
        skipLibCheck: true,
      },
      include: ['src/**/*.ts'],
    }),
  );
  writeFileSync(join(root, 'src/chart.ts'), fixture);
  rows = collectChartMap(root);
});
afterAll(() => {
  if (root) rmSync(root, { recursive: true, force: true });
});

it('indexes selector roots and the distinct parallel-foreach argument layout', () => {
  expect(rows.stages.find((r) => r.id === 'selector-root')).toMatchObject({
    name: 'Selector',
    description: { text: 'Root text.' },
  });
  expect(rows.stages.find((r) => r.id === 'fan-id')).toMatchObject({
    name: 'Fan out',
    description: { text: 'Fan text.' },
  });
});
it('indexes currently unused engine declaration doors rather than dropping them', () => {
  for (const method of [
    'addStreamingFunction',
    'addPausableFunction',
    'addListOfFunction',
    'startSelector',
    'addRetryLoop',
    'addDetachAndForget',
    'addDetachAndJoinLater',
  ]) {
    expect(
      [...rows.mounts, ...rows.stages].some((r) => r.method.includes(method)),
      method,
    ).toBe(true);
  }
});
it('renders the collected condition for a stage', () => {
  const row = rows.stages.find((r) => r.id === 'conditional');
  expect(row.context.join(' ')).toContain('on');
  const rendered = renderChartMap({ mounts: [], stages: [row] });
  expect(rendered).toContain('Enclosing control');
  expect(rendered).toContain('if (on)');
});
it.each(['callback', 'switch', 'logical', 'catch', 'optional'])(
  'does not assert absence for %s control',
  (id) => {
    const row = rows.stages.find((r) => r.id === id);
    expect(row, id).toBeDefined();
    expect(row.context.length, id).toBeGreaterThan(0);
  },
);
it.each(['spread-all', 'spread-tail'])(
  'keeps uncertain spread slots separate from absent values: %s',
  (name) => {
    const fragment = name === 'spread-all' ? 'b.addFunction(...(' : "b.addFunction('spread-tail'";
    const line = fixture.split('\n').findIndex((text) => text.includes(fragment)) + 1;
    const row = rows.stages.find((r) => r.line === line);
    expect(row.description.state).toBe('expression');
  },
);
it('does not promote a bound mixed overload to engine certainty', () => {
  expect(rows.stages.find((r) => r.id === 'mixed-bound')?.certainty).toBe('unresolved');
});
it.each([
  '<!-- generated by hand from notes -->',
  '<!-- DERIVED by analogy from a guide -->',
  '<!-- GENERATED by npm run missing; do not edit. -->',
  '<!-- GENERATED by npm run orphan; do not edit. -->',
])('keeps an unverified marker in authored evidence: %s', (marker) => {
  expect(
    isAuthoredDocument('# Guide\n\n' + marker + '\nA real explanation.', {
      'docs:generate': 'npm run docs:chart-map',
      'docs:chart-map': 'node scripts/generate-chart-map.mjs',
      orphan: 'node orphan.mjs',
    }),
  ).toBe(true);
});

it('does not mistake an incompatible ordinary start port for a chart declaration', () => {
  expect(rows.stages.some((row) => row.name.includes('ordinary-port-input'))).toBe(false);
});

it.each([
  ['addStreamingFunction', 'stream-id'],
  ['addPausableFunction', 'pause-id'],
  ['startSelector', 'start-id'],
  ['addRetryLoop', 'retry-id'],
  ['addDetachAndForget', 'forget-id'],
  ['addDetachAndJoinLater', 'join-id'],
])('reads the declared ID layout for %s', (method, id) => {
  expect([...rows.stages, ...rows.mounts].find((row) => row.method === method)?.id).toBe(id);
});
it('reads a streaming description after its stream ID', () => {
  expect(rows.stages.find((row) => row.id === 'stream-id')?.description.text).toBe(
    'Stream description.',
  );
});

it('refuses the removed check flag without changing the generated map', () => {
  const repository = resolve(__dirname, '../..');
  const file = join(repository, 'docs/chart-map.md');
  const before = readFileSync(file);
  const result = spawnSync(process.execPath, ['scripts/generate-chart-map.mjs', '--check'], {
    cwd: repository,
    encoding: 'utf8',
  });
  expect(result.status).not.toBe(0);
  expect(result.stderr).toContain('Usage: node scripts/generate-chart-map.mjs');
  expect(readFileSync(file)).toEqual(before);
});
