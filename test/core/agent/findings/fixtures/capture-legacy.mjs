import {createHash} from 'node:crypto';
import {gzipSync} from 'node:zlib';
import {writeFileSync,readFileSync,mkdirSync} from 'node:fs';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
const root=resolve(process.argv[2] ?? 'MISSING-BASELINE');
const output=resolve(process.argv[3] ?? 'MISSING-OUTPUT');
if(process.argv.length!==4)throw new Error('Usage: node test/core/agent/findings/fixtures/capture-legacy.mjs <installed agentfootprint10.9.0 folder> <new output folder>');
mkdirSync(output);
const pkg=JSON.parse(readFileSync(resolve(root,'package.json'),'utf8'));
if(pkg.version!=='10.9.0')throw new Error('Expected verified public1090');
const {Agent,defineTool,servedViews}=await import(pathToFileURL(resolve(root,pkg.exports['.'].import.default)));
const {mock}=await import(pathToFileURL(resolve(root,pkg.exports['./providers'].import.default)));
let n=0;
const provider=mock({respond(){n++;return n<3?{content:'',toolCalls:[{id:`legacy-${n}`,name:'lookup',args:n===2?{_findings:{basis:'direct',previous:[{toolCallId:'legacy-1',standing:'fact',assertions:[{subject:{kind:'fixture',id:'one'},predicate:'value',value:'synthetic-legacy-value'}]}]}}:{}}]}:'Synthetic legacy answer.';}});
const agent=Agent.create({provider,model:'mock',reactMode:'dynamic',maxIterations:5}).system('Inspect synthetic legacy data.').tool(defineTool({name:'lookup',description:'Read synthetic legacy data.',inputSchema:{type:'object',properties:{}},execute:()=> 'synthetic-legacy-value'})).findings().build();
await agent.run({message:'Read the synthetic fixture.'});
const snapshot=agent.getSnapshot();const views=servedViews(snapshot);
const raw=Buffer.from(JSON.stringify({sourceVersion:'10.9.0',snapshot,views},null,2)+'\n');
const gzip=gzipSync(raw,{level:9});
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
writeFileSync(resolve(output,'layout-legacy-10.9.0.json.gz'),gzip);
writeFileSync(resolve(output,'layout-legacy-10.9.0.manifest.json'),JSON.stringify({fixture:'layout-legacy-10.9.0.json.gz',sourcePackage:'agentfootprint@10.9.0',synthetic:true,modelCalls:0,uncompressedBytes:raw.length,uncompressedSha256:sha(raw),gzipSha256:sha(gzip),capturedViews:views.length},null,2)+'\n');
console.log(JSON.stringify({views:views.length,modelCalls:0}));
